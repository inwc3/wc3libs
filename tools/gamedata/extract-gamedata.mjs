// Builds the object-data snapshot that ObjMerger merges object modifications
// onto, by reading it straight out of a Warcraft III (Reforged) install with
// casc-ts.
//
//   node tools/gamedata/extract-gamedata.mjs [--wc3 <install dir>] [--casc <casc-ts dir>] [--out <zip>]
//
// Defaults: the standard install path, casc-ts checked out next to this
// repository (built with `npm run build`), and the resource BundledGameData
// loads. The zip is deterministic -- fixed timestamps, sorted entries -- so
// regenerating it from the same build changes nothing.
//
// Layers are stored under the names BundledGameData resolves:
//   base/       war3.w3mod
//   custom_v1/  war3.w3mod:_balance/custom_v1.w3mod
//   melee_v0/   war3.w3mod:_balance/melee_v0.w3mod
//   enus/       war3.w3mod:_locales/enus.w3mod

import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

function arg(name, fallback) {
    const i = process.argv.indexOf(`--${name}`);
    return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}

const wc3Dir = arg('wc3', 'C:/Program Files (x86)/Warcraft III');
const cascDir = path.resolve(arg('casc', path.join(repoRoot, '..', 'casc-ts')));
const outFile = path.resolve(arg('out', path.join(repoRoot,
    'src/main/resources/net/moonlightflower/wc3libs/app/objMerge/gamedata.zip')));

const LAYERS = [
    ['base', 'war3.w3mod'],
    ['custom_v1', 'war3.w3mod:_balance/custom_v1.w3mod'],
    ['melee_v0', 'war3.w3mod:_balance/melee_v0.w3mod'],
    ['enus', 'war3.w3mod:_locales/enus.w3mod'],
];

// Object tables, their metadata and the profile files objects are described
// in. Game constants, command cards and key bindings are not object data.
const WANTED = /^(units|doodads)\/[^/]+\.(slk|txt)$/;
const UNWANTED = /^units\/(misc|command|generalkeybind|unitglobalstrings|notused_)/;

function buildVersion() {
    const lines = fs.readFileSync(path.join(wc3Dir, '.build.info'), 'utf8').split(/\r?\n/).filter(Boolean);
    const header = lines[0].split('|').map(col => col.split('!')[0]);
    const active = lines.slice(1).map(line => line.split('|')).find(cols => cols[header.indexOf('Active')] === '1');

    return active ? active[header.indexOf('Version')] : 'unknown';
}

const { CascStorage, closeAllSegments } = await import(pathToFileURL(path.join(cascDir, 'dist', 'index.js')).href);

const storage = await CascStorage.openAsync(wc3Dir);
const entries = new Map();

try {
    for (const [, container] of LAYERS) await storage.readFileAsync(container);

    for (const [layer, container] of LAYERS) {
        const prefix = `${container}:`;

        for (const file of storage.listFiles()) {
            if (!file.startsWith(prefix)) continue;

            const rel = file.slice(prefix.length).toLowerCase();

            if (rel.includes(':') || !WANTED.test(rel) || UNWANTED.test(rel)) continue;

            entries.set(`${layer}/${rel}`, await storage.readFileAsync(file));
        }
    }
} finally {
    await closeAllSegments();
}

const version = buildVersion();

entries.set('manifest.properties', Buffer.from(
    `# Generated by tools/gamedata/extract-gamedata.mjs\nversion=${version}\nlayers=${LAYERS.map(([name]) => name).join(',')}\n`));

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, zip([...entries.entries()].sort(([a], [b]) => a.localeCompare(b))));

console.log(`wrote ${entries.size} entries for ${version} to ${path.relative(repoRoot, outFile)}`);

// --- a minimal deterministic zip writer (deflate, no extra fields) ---

function crc32(buf) {
    let crc = ~0;

    for (const byte of buf) {
        crc ^= byte;

        for (let k = 0; k < 8; k++) crc = (crc >>> 1) ^ (0xEDB88320 & -(crc & 1));
    }

    return ~crc >>> 0;
}

function zip(files) {
    const DOS_TIME = 0;
    const DOS_DATE = (1 << 5) | 1; // 1980-01-01
    const locals = [];
    const centrals = [];
    let offset = 0;

    for (const [name, data] of files) {
        const nameBytes = Buffer.from(name, 'utf8');
        const deflated = zlib.deflateRawSync(data, { level: 9 });
        const crc = crc32(data);

        const local = Buffer.alloc(30);
        local.writeUInt32LE(0x04034b50, 0);
        local.writeUInt16LE(20, 4);
        local.writeUInt16LE(0x0800, 6);
        local.writeUInt16LE(8, 8);
        local.writeUInt16LE(DOS_TIME, 10);
        local.writeUInt16LE(DOS_DATE, 12);
        local.writeUInt32LE(crc, 14);
        local.writeUInt32LE(deflated.length, 18);
        local.writeUInt32LE(data.length, 22);
        local.writeUInt16LE(nameBytes.length, 26);
        local.writeUInt16LE(0, 28);

        const central = Buffer.alloc(46);
        central.writeUInt32LE(0x02014b50, 0);
        central.writeUInt16LE(20, 4);
        central.writeUInt16LE(20, 6);
        central.writeUInt16LE(0x0800, 8);
        central.writeUInt16LE(8, 10);
        central.writeUInt16LE(DOS_TIME, 12);
        central.writeUInt16LE(DOS_DATE, 14);
        central.writeUInt32LE(crc, 16);
        central.writeUInt32LE(deflated.length, 20);
        central.writeUInt32LE(data.length, 24);
        central.writeUInt16LE(nameBytes.length, 28);
        central.writeUInt32LE(offset, 42);

        locals.push(local, nameBytes, deflated);
        centrals.push(central, nameBytes);
        offset += local.length + nameBytes.length + deflated.length;
    }

    const centralSize = centrals.reduce((sum, buf) => sum + buf.length, 0);
    const end = Buffer.alloc(22);
    end.writeUInt32LE(0x06054b50, 0);
    end.writeUInt16LE(files.length, 8);
    end.writeUInt16LE(files.length, 10);
    end.writeUInt32LE(centralSize, 12);
    end.writeUInt32LE(offset, 16);

    return Buffer.concat([...locals, ...centrals, end]);
}
